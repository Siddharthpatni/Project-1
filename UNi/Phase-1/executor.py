# ═══════════════════════════════════════════════════════════════════════════════
#  SECTION 2 :  Sandbox  (Safe Subprocess Runner)
# ═══════════════════════════════════════════════════════════════════════════════
# The sandbox runs a Python script in a completely isolated subprocess.
# It's the second line of defense (after the validator).
#
# What does "isolated" mean here?
#   - The subprocess runs in a temporary directory (not your project folder)
#   - Environment variables are stripped to a bare minimum
#   - Memory is capped (default: 512 MB) using resource.setrlimit on
#     Unix, or via Windows Job Objects where available
#   - Wall-clock time is capped (default: 60 seconds)
#   - Core dumps are disabled (Unix only)
#   - The process runs in its own process group (so we can kill the
#     whole tree if it spawns children)
#
# Cross-platform notes:
#   - resource.setrlimit / os.setsid / os.killpg are Unix-only.
#     On Windows we use CREATE_NEW_PROCESS_GROUP and taskkill.
#   - The PATH env var is built dynamically per platform.
#
# If the scraper crashes, hangs, or runs out of memory, the sandbox
# catches it cleanly and reports what happened.
#
# NOTE: This is the Python-level sandbox. For production, you'd also want
#       container-level isolation (Docker, gVisor, Firecracker, etc.).
# ═══════════════════════════════════════════════════════════════════════════════

@dataclass
class SandboxResult:
    """
    What comes back from running a script in the sandbox.

    returncode:  the subprocess exit code (0 = success, non-zero = error)
    stdout:      everything the script printed to stdout
    stderr:      everything the script printed to stderr
    elapsed:     how many seconds the script ran
    timed_out:   True if we had to kill the script because it ran too long
    """
    returncode: int
    stdout: str
    stderr: str
    elapsed: float
    timed_out: bool = False


def _build_preexec_fn(memory_mb: int):
    """
    Create a function that runs BEFORE the subprocess starts (Unix only).

    This is where we set the resource limits. It runs inside the child
    process, so the limits only affect the scraper — not our main script.

    We set:
    - RLIMIT_AS:   cap address space (total memory the process can allocate)
    - RLIMIT_CORE: disable core dumps (we don't need crash dumps)
    - os.setsid():  put the process in a new session group so we can
                    kill it and all its children with one signal

    On Windows this returns None — preexec_fn is not supported there.
    Windows sandboxing uses CREATE_NEW_PROCESS_GROUP instead.
    """
    if IS_WINDOWS:
        return None  # preexec_fn is not available on Windows

    def _apply():
        # Cap memory
        if resource is not None:
            try:
                bytes_cap = memory_mb * 1024 * 1024
                resource.setrlimit(resource.RLIMIT_AS, (bytes_cap, bytes_cap))
            except Exception:
                pass  # Some systems don't support RLIMIT_AS — that's okay

            # Disable core dumps
            try:
                resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
            except Exception:
                pass

        # New process group (so we can kill the entire tree later)
        os.setsid()

    return _apply


def _kill_process_tree(proc: subprocess.Popen):
    """
    Kill a subprocess and all its children.

    On Unix:    kill the process group via os.killpg (SIGKILL).
    On Windows: use taskkill /T /F to terminate the tree.
    """
    try:
        if IS_WINDOWS:
            # /T = kill child processes,  /F = force,  /PID = target process
            subprocess.call(
                ["taskkill", "/T", "/F", "/PID", str(proc.pid)],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
        else:
            os.killpg(proc.pid, signal.SIGKILL)
    except Exception:
        # Fallback: just kill the main process
        proc.kill()


def run_in_sandbox(
    script_path: str,
    workdir: str,
    timeout: int = SANDBOX_TIMEOUT,
    memory_mb: int = SANDBOX_MEMORY_MB,
) -> SandboxResult:
    """
    Run a Python script in a locked-down subprocess.

    The script runs with:
    - A forced working directory
    - A minimal environment (no access to your real env vars)
    - Memory and wall-clock caps
    - Stdout and stderr captured for analysis

    If the script exceeds the timeout, we kill the entire process group
    and return a result with timed_out=True.
    """

    # Minimal environment — the scraper only gets what it absolutely needs.
    # No API keys, no database URLs, no home directory access.
    if IS_WINDOWS:
        env = {
            "PATH": os.environ.get("PATH", ""),  # Windows needs its real PATH for python.exe
            "SYSTEMROOT": os.environ.get("SYSTEMROOT", r"C:\Windows"),
            "PYTHONPATH": workdir,
            "USERPROFILE": workdir,  # Windows "home" equivalent
            "TEMP": workdir,
            "TMP": workdir,
        }
    else:
        env = {
            "PATH": "/usr/local/bin:/usr/bin:/bin",
            "PYTHONPATH": workdir,      # so it can import its own modules
            "HOME": workdir,            # fake home directory
            "TMPDIR": workdir,          # temp files go in the sandbox
            "LC_ALL": "C.UTF-8",       # consistent encoding
            "LANG": "C.UTF-8",
        }

    t0 = time.time()

    # --- Spawn the subprocess ---
    # On Windows we use CREATE_NEW_PROCESS_GROUP so we can terminate the
    # entire tree later via taskkill.  On Unix we rely on preexec_fn to
    # call os.setsid() for the same purpose.
    popen_kwargs: dict = {
        "cwd": workdir,
        "env": env,
        "stdout": subprocess.PIPE,
        "stderr": subprocess.PIPE,
    }
    preexec = _build_preexec_fn(memory_mb)
    if preexec is not None:
        popen_kwargs["preexec_fn"] = preexec
    if IS_WINDOWS:
        popen_kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP

    try:
        proc = subprocess.Popen(
            [sys.executable, script_path],    # same Python interpreter as us
            **popen_kwargs,
        )
    except Exception as e:
        return SandboxResult(
            returncode=-1,
            stdout="",
            stderr=f"Failed to start sandbox subprocess: {e}",
            elapsed=0.0,
        )

    # --- Wait for it to finish (or kill it if it takes too long) ---
    try:
        stdout_bytes, stderr_bytes = proc.communicate(timeout=timeout)
        return SandboxResult(
            returncode=proc.returncode,
            stdout=stdout_bytes.decode("utf-8", errors="replace"),
            stderr=stderr_bytes.decode("utf-8", errors="replace"),
            elapsed=time.time() - t0,
        )
    except subprocess.TimeoutExpired:
        # The scraper took too long — kill the entire process group
        log.warning("Scraper timed out after %d seconds — killing process", timeout)
        _kill_process_tree(proc)
        stdout_bytes, stderr_bytes = proc.communicate()
        return SandboxResult(
            returncode=-9,
            stdout=stdout_bytes.decode("utf-8", errors="replace"),
            stderr=stderr_bytes.decode("utf-8", errors="replace"),
            elapsed=time.time() - t0,
            timed_out=True,
        )


# ═══════════════════════════════════════════════════════════════════════════════
#  SECTION 3 :  Executor  (Ties Sandbox + Results Together)
# ═══════════════════════════════════════════════════════════════════════════════
# The executor is the high-level function your code should call.
# It handles the full workflow:
#
#   1. Create a temporary directory
#   2. Write the scraper code as "scraper.py" inside it
#   3. Write a small "runner" script that imports scrape() and calls it
#   4. Run the runner in the sandbox
#   5. Read the results (what files were downloaded, any errors, etc.)
#   6. Clean up the temp directory
#
# The reason we have a separate "runner" script (instead of running
# scraper.py directly) is so we can:
#   - Catch exceptions and write them to a JSON file
#   - Measure elapsed time
#   - Capture the return value (list of downloaded files)
#
# The scraper itself just needs to define:
#   def scrape(url: str, output_dir: str) -> dict | list
# ═══════════════════════════════════════════════════════════════════════════════

@dataclass
class ExecutionResult:
    """
    The final result of executing a scraper.

    success:           did the scraper run without errors AND produce output?
    downloaded_files:  list of file paths the scraper saved
    scraper_output:    whatever the scrape() function returned (could be dict or list)
    stdout:            everything the scraper printed to stdout
    stderr:            everything the scraper printed to stderr
    runtime_seconds:   how long the scraper ran
    timed_out:         True if the scraper was killed for exceeding the time limit
    error:             error message if something went wrong (None if ok)
    """
    success: bool
    downloaded_files: list[str] = field(default_factory=list)
    scraper_output: dict | list | None = None
    stdout: str = ""
    stderr: str = ""
    runtime_seconds: float = 0.0
    timed_out: bool = False
    error: str | None = None


# This is the small "runner" script we inject into the temp directory.
# It imports the scraper, calls scrape(), and writes the result to a
# JSON file that we read back afterwards.
#
# Why not run scraper.py directly? Because we need to:
#   - Catch any exceptions the scraper throws
#   - Record the return value
#   - Measure how long it took
#
# The double-braces {{}} are because this is a .format() template —
# Python's format() uses {} for placeholders, so we escape literal
# braces by doubling them.
_RUNNER_SCRIPT = '''\
import json
import sys
import traceback
import time

# Make sure we can import the scraper from the working directory
sys.path.insert(0, {workdir!r})
from scraper import scrape

t0 = time.time()
try:
    # Call the scraper's main function
    output = scrape({url!r}, {output_dir!r})

    # Handle both return types:
    #   - dict  (new format: {{"tenders": [...], "downloaded_files": [...]}})
    #   - list  (old format: list of file paths)
    if isinstance(output, dict):
        result = {{
            "ok": True,
            "output": output,
            "files": output.get("downloaded_files", []),
            "elapsed": time.time() - t0,
        }}
    else:
        # Legacy format: scrape() returned a list of paths
        result = {{
            "ok": True,
            "output": output,
            "files": output if isinstance(output, list) else [],
            "elapsed": time.time() - t0,
        }}

except Exception as e:
    result = {{
        "ok": False,
        "error": str(e),
        "traceback": traceback.format_exc(),
        "elapsed": time.time() - t0,
    }}

# Write the result to a JSON file so the executor can read it back
with open({result_path!r}, "w") as f:
    json.dump(result, f, default=str)
'''


def execute(code: str, url: str, keep_downloads: str | None = None) -> ExecutionResult:
    """
    Execute a scraper in the sandbox and return the results.

    Args:
        code:            the Python source code of the scraper
        url:             the target URL to pass to scrape()
        keep_downloads:  if set, copy downloaded files here instead of
                         letting them be deleted with the temp directory

    Returns:
        ExecutionResult with success status, downloaded files, output, errors, etc.
    """

    with tempfile.TemporaryDirectory(prefix="phase1-run-") as workdir:
        work = Path(workdir)

        # Create a "downloads" subfolder — this is where the scraper saves files
        output_dir = work / "downloads"
        output_dir.mkdir()

        # Write the scraper code as scraper.py
        scraper_file = work / "scraper.py"
        scraper_file.write_text(code)

        # The runner will write its result here
        result_path = work / "result.json"

        # Generate the runner script with all paths filled in
        runner_code = _RUNNER_SCRIPT.format(
            workdir=str(work),
            url=url,
            output_dir=str(output_dir),
            result_path=str(result_path),
        )
        runner_path = work / "_runner.py"
        runner_path.write_text(runner_code)

        # --- Run it in the sandbox ---
        log.info("Starting sandbox execution (timeout=%ds, memory=%dMB)",
                 SANDBOX_TIMEOUT, SANDBOX_MEMORY_MB)
        sandbox = run_in_sandbox(
            script_path=str(runner_path),
            workdir=str(work),
            timeout=SANDBOX_TIMEOUT,
            memory_mb=SANDBOX_MEMORY_MB,
        )

        # --- Check if the runner even produced a result file ---
        # If result.json doesn't exist, the scraper probably crashed hard
        # (segfault, out of memory, killed by timeout, etc.)
        if not result_path.exists():
            return ExecutionResult(
                success=False,
                stdout=sandbox.stdout,
                stderr=sandbox.stderr,
                runtime_seconds=sandbox.elapsed,
                timed_out=sandbox.timed_out,
                error=(
                    "Scraper crashed without producing a result. "
                    "Likely cause: timeout, out of memory, or segfault."
                    + (" [TIMED OUT]" if sandbox.timed_out else "")
                ),
            )

        # --- Parse the result file ---
        try:
            payload = json.loads(result_path.read_text())
        except Exception as e:
            return ExecutionResult(
                success=False,
                stderr=sandbox.stderr,
                runtime_seconds=sandbox.elapsed,
                error=f"Runner produced invalid result.json: {e}",
            )

        # --- Did the scraper itself fail? ---
        if not payload.get("ok"):
            return ExecutionResult(
                success=False,
                stdout=sandbox.stdout,
                stderr=sandbox.stderr,
                runtime_seconds=payload.get("elapsed", sandbox.elapsed),
                error=payload.get("error") or "Unknown scraper error",
            )

        # --- Collect downloaded files ---
        # The runner reports which files scrape() said it downloaded.
        # We verify each one actually exists on disk.
        downloaded = []
        for filepath in payload.get("files", []):
            if os.path.isfile(filepath):
                downloaded.append(filepath)

        # Also check for any files in the downloads directory that the
        # scraper might have created but not reported in its return value
        for extra_file in output_dir.rglob("*"):
            if extra_file.is_file() and str(extra_file) not in downloaded:
                downloaded.append(str(extra_file))

        # --- Optionally copy downloads to a persistent location ---
        if keep_downloads and downloaded:
            keep_dir = Path(keep_downloads)
            keep_dir.mkdir(parents=True, exist_ok=True)
            saved_copies = []
            for filepath in downloaded:
                src = Path(filepath)
                dst = keep_dir / src.name
                # Handle filename collisions by adding a number
                if dst.exists():
                    stem, suffix = dst.stem, dst.suffix
                    counter = 1
                    while dst.exists():
                        dst = keep_dir / f"{stem}_{counter}{suffix}"
                        counter += 1
                shutil.copy2(str(src), str(dst))
                saved_copies.append(str(dst))
                log.info("Saved: %s", dst)
            downloaded = saved_copies

        return ExecutionResult(
            success=True,
            downloaded_files=downloaded,
            scraper_output=payload.get("output"),
            stdout=sandbox.stdout,
            stderr=sandbox.stderr,
            runtime_seconds=payload.get("elapsed", sandbox.elapsed),
        )



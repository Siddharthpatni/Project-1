def _print_validation_result(val: ValidationResult):
    """Pretty-print the validation result."""
    if val.ok:
        print("✅ Validation PASSED — no safety issues found.\n")
    else:
        print("❌ Validation FAILED — the following issues were found:\n")
        for err in val.errors:
            print(f"   ✖ {err}")
        print()
    if val.warnings:
        print("⚠  Warnings:")
        for warn in val.warnings:
            print(f"   • {warn}")
        print()


def _print_execution_result(result: ExecutionResult):
    """Pretty-print the execution result."""
    print(f"\n{'═'*60}")
    print(f"  Status:     {'✅ SUCCESS' if result.success else '❌ FAILED'}")
    print(f"  Runtime:    {result.runtime_seconds:.1f}s")
    if result.timed_out:
        print(f"  ⚠ TIMED OUT after {SANDBOX_TIMEOUT}s")
    print(f"  Files:      {len(result.downloaded_files)} downloaded")

    if result.error:
        print(f"  Error:      {result.error}")

    if result.downloaded_files:
        print(f"\n  Downloaded files:")
        for f in result.downloaded_files:
            size = os.path.getsize(f) if os.path.exists(f) else 0
            size_str = f"{size / 1024:.1f} KB" if size < 1_000_000 else f"{size / 1_000_000:.1f} MB"
            print(f"    📄 {Path(f).name}  ({size_str})")

    if result.scraper_output and isinstance(result.scraper_output, dict):
        tenders = result.scraper_output.get("tenders", [])
        if tenders:
            print(f"\n  Scraped tenders: {len(tenders)}")
            for i, t in enumerate(tenders[:5], 1):  # show first 5
                title = t.get("title", "untitled")
                print(f"    {i}. {title}")
            if len(tenders) > 5:
                print(f"    ... and {len(tenders) - 5} more")

    print(f"{'═'*60}\n")

    # Show stdout/stderr if there's something interesting
    if result.stdout.strip():
        print("── stdout ──")
        print(result.stdout[:3000])
        if len(result.stdout) > 3000:
            print(f"... ({len(result.stdout)} chars total, truncated)")
        print()

    if result.stderr.strip():
        print("── stderr ──")
        print(result.stderr[:3000])
        if len(result.stderr) > 3000:
            print(f"... ({len(result.stderr)} chars total, truncated)")
        print()


def cmd_validate(args: argparse.Namespace):
    """Just validate the scraper code — don't run it."""
    code = Path(args.file).read_text()
    log.info("Validating: %s", args.file)

    result = validate(code)
    _print_validation_result(result)

    # Exit with non-zero status if validation failed
    sys.exit(0 if result.ok else 1)


def cmd_execute(args: argparse.Namespace):
    """Execute the scraper in sandbox — skip validation."""
    code = Path(args.file).read_text()
    log.info("Executing: %s against %s (no validation)", args.file, args.url)

    result = execute(code, args.url, keep_downloads=args.keep_downloads)
    _print_execution_result(result)

    sys.exit(0 if result.success else 1)


def cmd_run(args: argparse.Namespace):
    """Validate first, then execute if safe. This is the recommended command."""
    code = Path(args.file).read_text()

    # Step 1: Validate
    log.info("Step 1/2: Validating %s ...", args.file)
    val = validate(code)
    _print_validation_result(val)

    if not val.ok:
        print("❌ Aborting — scraper code failed safety checks.")
        print("   Fix the issues above, or use `execute` to skip validation.\n")
        sys.exit(1)

    # Step 2: Execute
    log.info("Step 2/2: Executing %s against %s ...", args.file, args.url)
    result = execute(code, args.url, keep_downloads=args.keep_downloads)
    _print_execution_result(result)

    sys.exit(0 if result.success else 1)



#!/usr/bin/env python3
"""
Phase-1 : Scraper Executor  (Standalone)
==========================================

What does this script do?
-------------------------
It takes a scraper file (generated by generator.py or written by hand)
and runs it safely in a sandboxed subprocess. Think of it as a "test
bench" for scrapers — it runs the code, captures everything that
happens, and tells you exactly what went right or wrong.

The scraper never touches your real system. It runs in an isolated
subprocess with:
  - A temporary working directory (deleted after the run)
  - A memory cap (default 512 MB)
  - A wall-clock timeout (default 60 seconds)
  - A stripped-down environment (no access to your env vars, home dir, etc.)

Before running, we also do a static safety check (validator) to catch
dangerous code patterns (eval, exec, subprocess, etc.) BEFORE they
ever execute.

Three things this file does
----------------------------
1. VALIDATE  – Parse the scraper code and check for forbidden imports or
               function calls (e.g. subprocess, eval, exec, os.system).
               This is a fast AST-based check, no code is actually run.

2. EXECUTE   – Run the scraper in a sandboxed subprocess against a given
               URL and collect the results.

3. FULL RUN  – Validate first, then execute if safe. This is the default.

Usage
-----
    # Run a scraper (validates first, then executes):
    python executor.py run scraper_example_com.py "https://example.com/tenders"

    # Just validate (no execution):
    python executor.py validate scraper_example_com.py

    # Execute without validation (skip safety checks — use carefully!):
    python executor.py execute scraper_example_com.py "https://example.com/tenders"

    # Keep downloaded files in a specific directory:
    python executor.py run scraper.py "https://example.com" --keep-downloads ./results

Environment Variables (optional, set in shell or .env):
    SANDBOX_TIMEOUT    – max seconds for scraper to run (default: 60)
    SANDBOX_MEMORY_MB  – max memory in MB (default: 512)
    LOG_LEVEL          – logging verbosity (default: INFO)

No project imports. No external dependencies. Just Python 3.10+ stdlib.
"""
